from io import BytesIO

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

ALLOWED = {
    "Музыкальное произведение с текстом",
    "Музыкальное произведение без текста",
}

def add_text(paragraph, text, bold=False):
    run = paragraph.add_run(text)
    run.bold = bold
    return run

def add_underline(paragraph, color="000000", sz="12", space="1"):
    pPr = paragraph._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), sz)
    bottom.set(qn('w:space'), space)
    bottom.set(qn('w:color'), color)
    pBdr.append(bottom)
    pPr.append(pBdr)


def add_section_title(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(0x00, 0x00, 0x00)

    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    return p


def add_list_item(doc, text):
    p = doc.add_paragraph(text)
    pf = p.paragraph_format
    pf.left_indent = Pt(25)
    pf.first_line_indent = Pt(-25)
    pf.space_after = Pt(4)
    return p


def build_agreement(work_type: str) -> bytes:
    if work_type not in ALLOWED:
        work_type = "Музыкальное произведение с текстом"

    doc = Document()
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("СОГЛАШЕНИЕ СОАВТОРОВ ПРОИЗВЕДЕНИЯ")
    run.bold = True
    run.font.size = Pt(14)

    add_underline(title, sz="12", space="4")

    doc.add_paragraph(
        f'г. __________{" " * 118}"___"________ 20__ г.'
    )
    paragraph = doc.add_paragraph()

    add_text(paragraph,
             f"Гр. {'_' * 48}, паспорт: серия {'_' * 8}, № {'_' * 8}, выданный {'_' * 24}, проживающий по адресу: {'_' * 48}, именуемый в дальнейшем «")
    add_text(paragraph, "Соавтор", bold=True)
    add_text(paragraph,
             f"», с одной стороны, и гр. {'_' * 48}, паспорт: серия {'_' * 8}, № {'_' * 8}, выданный {'_' * 24}, проживающий по адресу: {'_' * 48}, именуемый в дальнейшем «")
    add_text(paragraph, "Соавтор 2", bold=True)
    add_text(paragraph, f"», с другой стороны, именуемые в дальнейшем «")
    add_text(paragraph, "Стороны", bold=True)
    add_text(paragraph, f"», заключили настоящий договор, в дальнейшем «")
    add_text(paragraph, "Договор", bold=True)
    add_text(paragraph, "», о нижеследующем:")

    for r in (
            f"стороны являются соавторами произведения – {'_' * 48} – полное описание смотри в п.1.1 соглашения;",
            "для возникновения, осуществления и защиты авторских прав на произведение, являющееся предметом настоящего соглашения (или отдельные его части), не требуется регистрация произведения или соблюдение каких-либо иных формальностей;",
            "произведение не отчуждено, на него не выдана лицензия третьим лицам;",
            "права на произведение принадлежат соавторам совместно.",
    ):
        add_list_item(doc, r)

    add_section_title(doc, "1. ОПРЕДЕЛЕНИЕ ТЕРМИНОВ СОГЛАШЕНИЯ")
    doc.add_paragraph(
        "1.1. Стороны совместно создали музыкальное произведение с текстом (далее – «Произведение»). "
        "Стороны также совместно осуществили запись исполнения данного музыкального произведения "
        "(далее – «Исполнение») и совместно изготовили фонограмму музыкального произведения, "
        "в которой зафиксирована запись Исполнения (далее – «Фонограмма»). В целях настоящего "
        "Соглашения Произведение, Исполнение и Фонограмма далее именуются как «Объекты»."
    )
    doc.add_paragraph("1.2. Стороны согласовали следующую спецификацию Объектов:")
    doc.add_paragraph("Музыкальное Произведение:")

    table1 = doc.add_table(rows=2, cols=5)
    table1.style = "Table Grid"
    for i, h in enumerate(
            ["Название Произведения", "Тип Произведения", "Автор(ы) музыки", "Автор(ы) текста", "Дата создания"]
    ):
        table1.rows[0].cells[i].text = h
        for run in table1.rows[0].cells[i].paragraphs[0].runs:
            run.bold = True
    table1.rows[1].cells[0].text = f"«{'_' * 16}»"
    table1.rows[1].cells[1].text = work_type
    table1.rows[1].cells[2].text = "ФИО"
    table1.rows[1].cells[3].text = "ФИО"
    table1.rows[1].cells[4].text = ""

    doc.add_paragraph("Запись Исполнения и Фонограмма:")
    table2 = doc.add_table(rows=2, cols=5)
    table2.style = "Table Grid"
    for i, h in enumerate(
            [
                "Название Фонограммы",
                "Исполнители",
                "Характеристики",
                "Продолжительность Фонограммы",
                "Изготовитель(и) Фонограммы",
            ]
    ):
        table2.rows[0].cells[i].text = h
        for run in table2.rows[0].cells[i].paragraphs[0].runs:
            run.bold = True
    table2.rows[1].cells[0].text = f"«{'_' * 16}»"
    table2.rows[1].cells[1].text = "ФИО"
    table2.rows[1].cells[2].text = f"Жанр: {'_' * 10}\nBpm: {'_' * 10}\nKbps: {'_' * 10}\nТональность: {'_' * 10}"
    table2.rows[1].cells[3].text = f"{'_' * 3} мин. {'_' * 3} сек."
    table2.rows[1].cells[4].text = "ФИО\n\n\nФИО"

    doc.add_paragraph(
        f"1.3. Материальный носитель – произведение имеется в {'_' * 8} экземплярах на {'_' * 24}."
    )
    doc.add_paragraph(
        f"1.4. Произведение находится по адресу: {'_' * 48}."
    )
    doc.add_paragraph(f"1.5. Срок действия авторских прав составляет {'_' * 8} лет.")

    add_section_title(doc, "2. ПРЕДМЕТ СОГЛАШЕНИЯ")
    doc.add_paragraph(
        "2.1. Каждый из соавторов может использовать произведение по своему усмотрению, в пределах, "
        "установленных Гражданским кодексом Российской Федерации и настоящим соглашением."
    )
    doc.add_paragraph("2.2. Каждый соавтор обязан:")
    for o in (
            "соблюдать права и законные интересы другого соавтора, установленные законом и настоящим соглашением, в том числе и после его расторжения;",
            "при осуществлении правомочий автора в отношении произведения соавторы руководствуются действующим законодательством;",
            "совместно распоряжаться исключительным правом на произведение;",
            "не чинить препятствия другому соавтору в распоряжении исключительным правом на произведение, в том числе путем злоупотребления правом;",
            "проявлять надлежащую заботу об экземплярах произведения, принимать все необходимые меры для предотвращения их уничтожения или повреждения, а также для устранения угрозы его уничтожения или повреждения, в том числе производить необходимые расходы за счет собственного имущества или общего имущества соавторов;",
            "уведомлять другого соавтора обо всех угрозах утраты или оспаривания прав на произведение.",
    ):
        add_list_item(doc, o)
    doc.add_paragraph("2.3. Каждый из соавторов имеет право:")
    for r in (
            "использовать произведение в личных целях не для извлечения прибыли;",
            "перерабатывать произведение или отдельные его части. При возникновении нового произведения такой соавтор становится единственным автором нового произведения.",
    ):
        add_list_item(doc, r)
    doc.add_paragraph(
        "2.4. В случае утраты одним из соавторов экземпляра произведения стороны восстанавливают "
        "(изготавливают) такой (еще один) экземпляр произведения совместно."
    )
    doc.add_paragraph(
        f"2.5. Территория, на которой допускается использование произведения: {'_' * 48}."
    )
    doc.add_paragraph(
        "2.6. Переход исключительного права на произведение к новому правообладателю не является "
        "основанием для изменения или расторжения настоящего соглашения."
    )

    add_section_title(doc, "3. ОТВЕТСТВЕННОСТЬ СОАВТОРОВ")
    doc.add_paragraph(
        "3.1. Каждый из соавторов несет ответственность в отношении принятых на себя обязательств "
        "перед третьими лицами и кредиторами в пределах принадлежащего ему имущества, в том числе "
        "в пределах принадлежащей ему доли в общем имуществе соавторов. При недостаточности этого "
        "имущества кредитор не вправе обращать взыскание на имущество другого соавтора."
    )
    doc.add_paragraph(
        "3.2. Сторона, которая не выполнила обязательства по соглашению, обязана возместить другой "
        "Стороне причиненные ей убытки."
    )
    doc.add_paragraph(
        "3.3. Уплата неустойки и возмещение убытков в случае ненадлежащего исполнения или "
        "неисполнения обязательства не освобождают Сторону от исполнения обязательства в натуре."
    )

    add_section_title(doc, "4. ПОСТУПЛЕНИЯ, РАСХОДЫ")
    doc.add_paragraph(
        "4.1. Вознаграждение за предоставленные на произведение лицензии стороны распределяют "
        f"в следующем порядке: соавтору 1 причитается {'_' * 7}%, соавтору 2 причитается {'_' * 7}% "
        "от полученной суммы."
    )
    doc.add_paragraph(
        "4.2. Вознаграждение за отчуждение произведения стороны распределяют в следующем порядке: "
        f"соавтору 1 причитается {'_' * 7}%, соавтору 2 причитается {'_' * 7}% от полученной суммы."
    )
    doc.add_paragraph(
        "4.3. Иные доходы, поступившие от использования произведения, стороны распределяют "
        f"в следующем порядке: соавтору 1 причитается {'_' * 7}%, соавтору 2 причитается {'_' * 7}% "
        "от полученной суммы."
    )
    doc.add_paragraph(
        "4.4. Расходы, связанные с созданием произведения и поддержанием авторских прав, стороны "
        f"несут в следующем порядке: соавтору 1 причитается {'_' * 7}%, соавтору 2 причитается {'_' * 7}% "
        "от полученной суммы."
    )
    doc.add_paragraph(
        "4.5. Все сборы, налоги и другие расходы, связанные с заключением и выполнением настоящего "
        "соглашения, стороны несут самостоятельно в соответствии с действующим законодательством."
    )

    add_section_title(doc, "5. ФОРС-МАЖОР")
    doc.add_paragraph(
        "5.1. Стороны освобождаются от ответственности за частичное или полное неисполнение "
        "обязательств по настоящему соглашению, если это неисполнение явилось следствием "
        "обстоятельств непреодолимой силы. Под обстоятельствами непреодолимой силы понимаются "
        "обстоятельства, возникшие после заключения настоящего соглашения в результате событий "
        "чрезвычайного характера, которые Стороны не могли ни предвидеть, ни предотвратить "
        "разумными мерами. К таким обстоятельствам чрезвычайного характера относятся: наводнение, "
        "пожар, землетрясение или иные явления природы, а также войны, военные действия, акты или "
        "действия государственных органов и любые другие обстоятельства вне разумного контроля Сторон."
    )
    doc.add_paragraph(
        "5.2. При наступлении указанных в п.5.1 обстоятельств Сторона должна без промедления "
        "известить о них в письменной форме другую Сторону. Извещение должно содержать данные о "
        "характере обстоятельств, а также, по возможности, оценку их влияния на возможность "
        "исполнения Стороной своих обязательств по настоящему соглашению и срок исполнения обязательств."
    )
    doc.add_paragraph(
        "5.3. При прекращении указанных в п.5.1 обстоятельств Сторона должна без промедления "
        "известить об этом другую Сторону в письменном виде. В извещении должен быть указан срок, "
        "в который предполагается исполнить обязательства по настоящему соглашению."
    )
    doc.add_paragraph(
        "5.4. Если Сторона не направит или несвоевременно направит извещение, предусмотренное "
        "в п.п.5.2 и 5.3, то она обязана возместить другой Стороне убытки, причиненные "
        "неизвещением или несвоевременным извещением."
    )
    doc.add_paragraph(
        "5.5. Сторона, ссылающаяся на обстоятельства, указанные в п.5.1, должна в течение "
        "разумного срока передать другой Стороне по ее просьбе удостоверение торговой палаты "
        "или иной компетентной организации о наличии этих обстоятельств."
    )
    doc.add_paragraph(
        "5.6. В случаях, предусмотренных в п.5.1, срок выполнения обязательств по настоящему "
        "соглашению отодвигается соразмерно времени, в течение которого действуют такие "
        "обстоятельства и их последствия."
    )
    doc.add_paragraph(
        "5.7. В случаях, когда указанные в п.5.1 обстоятельства и их последствия продолжают "
        f"действовать более {'_' * 8} месяцев или когда при наступлении данных обстоятельств "
        "становится ясным, что они и их последствия будут действовать более этого срока, "
        "Стороны в возможно более короткий срок проведут переговоры с целью выявления приемлемых "
        "для них альтернативных способов исполнения настоящего соглашения. При этом любая Сторона "
        "может отказаться от дальнейшего исполнения настоящего соглашения. В этом случае каждая "
        "Сторона обязана вернуть другой Стороне все полученное по настоящему соглашению. "
        "Убытки возмещению не подлежат."
    )

    add_section_title(doc, "6. ЗАЩИТА ПРАВ НА ПРОИЗВЕДЕНИЕ")
    doc.add_paragraph(
        "6.1. Если после заключения соглашения какое-либо третье лицо оспорит права авторов на "
        "произведение, то Стороны незамедлительно, после того как им станет об этом известно, "
        "предпримут совместные действия по защите своих прав, а также осуществят другие "
        "мероприятия, связанные с выполнением соглашения."
    )
    doc.add_paragraph(
        "6.2. Понесенные Сторонами расходы и убытки в результате урегулирования указанных претензий "
        "или окончания судебных процессов будут распределены между Сторонами согласно п.4.2 соглашения."
    )

    add_section_title(doc, "7. СРОК ДЕЙСТВИЯ СОГЛАШЕНИЯ. УСЛОВИЯ ЕГО ИСПОЛНЕНИЯ И РАСТОРЖЕНИЯ")
    doc.add_paragraph(
        "7.1. Соглашение вступает в силу и становится обязательным для сторон с момента его заключения."
    )
    doc.add_paragraph(
        f"7.2. Соглашение действует в течение {'_' * 8} лет с момента заключения."
    )
    doc.add_paragraph(
        "7.3. В случае прекращения исключительного права соглашение прекращается."
    )
    doc.add_paragraph(
        "7.4. Окончание срока действия соглашения не освобождает стороны от ответственности за его нарушение."
    )

    add_section_title(doc, "8. КОНФИДЕНЦИАЛЬНОСТЬ")
    doc.add_paragraph(
        "8.1. Условия настоящего договора и дополнительных соглашений к нему конфиденциальны "
        "и не подлежат разглашению."
    )

    add_section_title(doc, "9. РАЗРЕШЕНИЕ СПОРОВ")
    doc.add_paragraph(
        "9.1. Все споры и разногласия, которые могут возникнуть между сторонами по вопросам, "
        "не нашедшим своего разрешения в тексте данного договора, будут разрешаться путем "
        "переговоров на основе действующего законодательства и обычаев делового оборота."
    )
    doc.add_paragraph(
        "9.2. При неурегулировании в процессе переговоров спорных вопросов споры разрешаются "
        "в суде в порядке, установленном действующим законодательством."
    )

    add_section_title(doc, "10. ПРОЧИЕ УСЛОВИЯ")
    doc.add_paragraph(
        "10.1. К отношениям Сторон по тем вопросам, которые не урегулированы или не полностью "
        "урегулированы соглашением, применяется законодательство Российской Федерации."
    )
    doc.add_paragraph(
        "10.2. Все изменения и дополнения к настоящему соглашению должны быть совершены в письменной форме."
    )
    doc.add_paragraph(
        "10.3. Настоящее соглашение совершено в двух экземплярах – по одному экземпляру для каждой "
        "Стороны, причем оба текста имеют одинаковую силу."
    )

    add_section_title(doc, "11. РЕКВИЗИТЫ И ПОДПИСИ СТОРОН")
    doc.add_paragraph(
        f"Соавтор 1: {'_' * 72}"
    )
    doc.add_paragraph(
        f"телефон: {'_' * 17}, электронная почта: {'_' * 24}"
    )
    doc.add_paragraph("")
    doc.add_paragraph(
        f"Соавтор 2: {'_' * 72}"
    )
    doc.add_paragraph(
        f"телефон: {'_' * 17}, электронная почта: {'_' * 24}"
    )
    doc.add_paragraph("")
    doc.add_paragraph(f"Соавтор 1:  {'_' * 15} / {'_' * 15} /")
    doc.add_paragraph("            (подпись)         (Ф.И.О.)")
    doc.add_paragraph("")
    doc.add_paragraph(f"Соавтор 2:  {'_' * 15} / {'_' * 15} /")
    doc.add_paragraph("            (подпись)         (Ф.И.О.)")

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()


